/**
 * Core Language Management Engine
 */
function getCurrentLanguage() {
    return localStorage.getItem('kashirak_lang') || 'ar';
}

function applyLanguage(lang) {
    if (!KASHIRAK_TRANSLATIONS[lang]) lang = 'ar';

    // 1. Set HTML tag attributes
    document.documentElement.lang = lang;
    document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';
    document.body.classList.toggle('lang-en', lang === 'en');
    document.body.classList.toggle('lang-ar', lang === 'ar');

    // 2. Translate all elements with data-i18n
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (KASHIRAK_TRANSLATIONS[lang][key] !== undefined) {
            el.innerHTML = KASHIRAK_TRANSLATIONS[lang][key];
        }
    });

    // 3. Translate HTML content blocks (like lessons)
    const htmlElements = document.querySelectorAll('[data-i18n-html]');
    htmlElements.forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (KASHIRAK_LESSON_CONTENTS[lang] && KASHIRAK_LESSON_CONTENTS[lang][key] !== undefined) {
            el.innerHTML = KASHIRAK_LESSON_CONTENTS[lang][key];
        }
    });

    // 4. Translate attributes: title, placeholder, alt, aria-label
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (KASHIRAK_TRANSLATIONS[lang][key]) el.setAttribute('title', KASHIRAK_TRANSLATIONS[lang][key]);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (KASHIRAK_TRANSLATIONS[lang][key]) el.setAttribute('placeholder', KASHIRAK_TRANSLATIONS[lang][key]);
    });
    document.querySelectorAll('[data-i18n-alt]').forEach(el => {
        const key = el.getAttribute('data-i18n-alt');
        if (KASHIRAK_TRANSLATIONS[lang][key]) el.setAttribute('alt', KASHIRAK_TRANSLATIONS[lang][key]);
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
        const key = el.getAttribute('data-i18n-aria');
        if (KASHIRAK_TRANSLATIONS[lang][key]) el.setAttribute('aria-label', KASHIRAK_TRANSLATIONS[lang][key]);
    });

    // 5. Update Switcher Button Label
    const switcherBtns = document.querySelectorAll('.lang-switcher-btn');
    switcherBtns.forEach(btn => {
        const label = btn.querySelector('.lang-name');
        if (label) {
            label.textContent = (lang === 'ar') ? 'English' : 'العربية';
        }
        btn.setAttribute('aria-label', (lang === 'ar') ? 'Switch to English' : 'التبديل إلى العربية');
    });

    // 6. Dispatch custom event for page-specific reactive scripts
    window.dispatchEvent(new CustomEvent('kashirak_lang_changed', { detail: { lang } }));
}

function toggleLanguage() {
    const current = getCurrentLanguage();
    const next = (current === 'ar') ? 'en' : 'ar';
    localStorage.setItem('kashirak_lang', next);
    applyLanguage(next);
}

// Auto-initialize on load
document.addEventListener('DOMContentLoaded', () => {
    const saved = getCurrentLanguage();
    applyLanguage(saved);

    // Bind all switcher buttons
    document.querySelectorAll('.lang-switcher-btn').forEach(btn => {
        btn.addEventListener('click', (e) => {
            e.preventDefault();
            toggleLanguage();
        });
    });
});
